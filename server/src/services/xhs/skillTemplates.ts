// 内置写作 skill 模板：一键导入到「写作 Skill 调试台」，之后用户自己随便改。
//
// 为什么是**一个主文件**而不是照搬原 skill 的 main + references 多文件结构：
// `uws.assembleSkillBody` 会把**没被 {{ref}} 引用的引用文件也全部拼在末尾**，
// 所以这里的多文件不存在「按任务懒加载」，只有「每次生成都全量塞进 prompt」。
// 原 skill 的 1100 行分文件在这个平台上等于每条请求都背着 1100 行，
// 拆文件除了让人误以为省了 token 之外没有任何作用。要拆只能靠用户自己删。

export interface SkillTemplate {
  id: string;
  name: string;
  description: string;
  /**
   * 出处，展示给用户，避免以后看着这份规范不知道它从哪来。
   * 叫 origin 不叫 source：`aiAppRegistry.test.ts` 全仓扫 `source: '…'` 字面量
   * 去核 AI 应用白名单，占用这个键名会让那个守卫报一条假失败。
   */
  origin: string;
  mainBody: string;
}

const HUMAN_WRITING = `# 活人感写作（蒸馏版）

这份规范只管一件事：让人读出对面是个具体的人，而不是一台在完成写作任务的模型。
它管材料、说话位置、句法和成稿禁令。**它不管**标题公式、emoji、话题标签、
排版和结尾互动——那些交给平台底座和别的 skill，本规范不去覆盖。

平台已声明文体是**金句/文案体**或**抒情/随笔体**时，本规范的散文句法（主干先出、
长短句差、砍金句、禁排比）不适用，按那个文体的手艺写；只有下面「成稿绝对不能出现」
那一节仍然全篇有效。

## 一、动笔前先数材料

活人感首先来自材料，其次来自说话位置，最后才是语气。口头禅和网络梗不是活人感。

能撑住文章的只有三类东西：作者亲历的经过、数字、原话、动作；查得到且能核对的
案例、流程、价格、时间；明确授权虚构时创造的人物动作与场景变化。

- 短笔记至少清点出 **3 件**具体材料，正文打算写到 800 字以上至少 **5 件**，
  每件都要说得出它来自作者哪句话或哪个来源。「有个朋友」「据说很多人」不算一件。
- 模型临时想出的例子、没有来源的典型场景、常识推演、把一个道理换四种说法，
  全都不算材料。手里三条抽象观点，就只写得出三段。
- 材料不够时只有三条路：能查的先查；只能靠作者本人的，**一次问完最多三个问题**
  （你和这件事实际发生过什么关系／哪个数字、动作或原话最让你在意／你现在最想说的
  判断是什么），此时不要同时交稿；用户不让问又查不到，**就把篇幅缩短**，
  宁可短，不许用假例子和重复解释填满。
- 每段写完在心里指一下它靠哪件材料站住。答案是「这是上一段的进一步解释」，
  这段就该删。

## 二、找到说话位置

内部回答清楚、不要写给读者看：谁在说这件事，他凭什么知道，哪些地方只是推测；
什么事让他现在想说；他手里最硬的三样材料是什么；他对哪一点有明确判断，这判断
到哪里为止；读者读完上一段最自然会追问什么。

作者可以是亲历者、调查者、行内人，也可以只是认真查完资料的人。四种都行，
但不能把查资料写成亲历，不能把猜测写成内幕。用户只说「看见过」，不许写成「试过」。

现实内容里最有活人感的，往往是知识的来路：作者哪里知道这件事，起初哪里想错了，
哪条材料改了他的判断，哪一块到现在还拿不准。每篇自然出现一两项就够，凑齐就是新模板。

## 三、怎么写

- 开头尽快碰到事情：直接给答案、讲刚发生的一幕，或从一个反常的小事实说起。
  不要预告全文结构，不要「我将从三个方面……」。
- 句子先把主干交出来：先说谁做了什么，再补时间、原因、条件和例子。
  一句话里堆到三四个「的」就重写。
- 让句子顺着刚出现的人或物往后长，指向清楚时不必每句重念主语，也不必给每个小句
  配连接词。「因为／所以／同时／此外／然而」删掉一半，读不断的地方就不用补回来。
- 段落必须带来新东西：新事实、新动作、新例子、新区别或新后果。同一观点换个说法不算推进。
- 长短句要有高低差：十个字的句子要能挨着四十个字的句子。普通的地方用普通句子结束，
  不要每段都用一句短判断收尾。单句成段只留给确实需要停一下的地方。
- 该重复的词就重复。为躲重复频繁换同义词，文章会变油。
- 白话打底。「买／购买」「改／修改」「看／使用」按说话者和场合选，不为了显稳重
  全换长词，也不为了显古朴硬压成单字。成语典故只在意思准确、读者不用查、
  比白话更省时才留。
- 细节必须有工作：一笔价格能说明风险，一段原话能说明关系，一次失败能说明旧办法
  为什么不行。凌晨三点、第三根烟、桌上的冷咖啡、窗外的雨——没有来源又不改变后文的，
  一律删掉。假细节越具体，AI 味越重。
- 动作、原话或细节已经把情绪写出来了就停手，不要追一句替读者解释。
- 判断可以尖锐、可以有偏见，把依据放在附近。材料支持七成就说到七成，
  剩下三成承认不知道，比再补五个限定词可信。
- 写到事情讲完就停。不要升华、不要首尾呼应、不要在末段重新摘要全文。

方向校准（同一件事的两种写法）：

> 坏：真正让他下定决心的，不是那次失败本身，而是他终于看清了一个残酷的真相。
> 好：他折腾了几年，一直没挣到稳定的钱。后来老同事找过来，问他愿不愿意一起做项目，
> 他才换了方向。收入会不会稳定，当时没人知道。

前一种只有姿势，后一种给了动作、条件和风险。

## 四、成稿绝对不能出现

覆盖标题、小标题、正文和引用转述。这里禁的是**修辞动作**，换一套字继续做同一个
动作仍然算命中。

- **翻案腔**：先立一个读者并没有的误解，再推翻它给下文抬价。已知外衣有
  「不是A而是B」「并非A而是B」「不在于A而在于B」「与其说A不如说B」「表面上A实际上B」
  「看似A实则B」「你以为A其实B」「回头才发现」「说到底」「答案恰恰相反」
  「A不重要，重要的是B」以及一切变形。清单是举例不是边界。要下判断就从正面下，
  先给判断，再给依据。只有文章真的用材料走过了从误解到修正的过程，才可以保留一次
  自我修正，而且不能穿上面任何一件外衣。
- **三项以上的同构排比**。两项为限，第三项换说法或删掉。
- **给抽象名词配具体动词的抒情**：时间不会保管细节，焦虑不会显出形状，
  岁月不会磨平什么。真的在写具体事物时不受影响。
- **动词名词化**：「完成了对流程的优化」写成「把流程改顺了」，「实现了效率提升」
  写成「快了多少、省了几个人」。看到「进行／实现／完成／开展」带一个动名词就还原。
- **破折号 — —— –** 一个都不许有。
- **冒号只用来引出人物的直接原话**。「一句话总结：」「核心是：」这类提示性冒号禁止
  （网址、代码除外）。
- 不用「说白了」「说穿了」「先说结论」。
- 不用「更微妙的是」「还有一层」「只说对了一半」「值得注意的是」「需要指出的是」
  「从某种意义上说」当洞察路标。
- **黑话禁词**：赋能、抓手、商业闭环、能力沉淀、拉通、底层逻辑、顶层设计、
  认知跃迁、价值释放、降本增效、内容矩阵、全链路、组合拳、打开想象空间、
  结构性机会、深层逻辑、技术底座、认知增量、迭代闭环。改成人、动作、钱、时间和后果。
  （沉淀、颗粒度、对齐、链路、心智、方法论、闭环这些只在给普通事情抬价时改，
  说本义时不管。）
- **非虚构内容不用仓库、抽屉、温度、死亡、坍塌、浪潮、钥匙、底座**这类借喻包装
  抽象概念。真的在写这些东西时不受影响。抒情词（安放、抵达、微光、褶皱、丰盈、
  滚烫、剥开）写具体事物时是好词，给抽象概念穿衣服时删掉。
- 结尾不许升到时代、文明、未来、世界、所有人。正文没有一直在处理这个尺度，
  结尾就回到具体事实和当前判断。
- 原话命中这些禁令时改成转述或省略，不能靠引号保留。

「不只……还……」是正常的递进，可以用；它出现在翻案位置给下文抬价时，按翻案腔处理。

改违禁句的办法只有一种：找到它原本想说的那件事，用普通句子说出来。
不要去找另一种漂亮句式替换。

## 五、交稿前冷读

忘掉上面所有规则，只回答五句：哪里让我相信作者确实知道这件事；哪里让我愿意继续读；
哪一段换一个模型也能原样写出来；哪句话说得比材料大；文章在哪一句其实已经结束了。

第三类段落补材料或删掉，第四句删掉，第五句之后的全部砍掉。
`;

