// 品牌咨询的阶段清单 —— 第一层「四看 → 四问 → 四大成」+ 第二层内容营销 + 第三层数字化营销，
// 方法论来自品牌占位系统（zixun/references/methodology.md）。
//
// 这份清单是**唯一事实源**，不落库：阶段是产品形态的一部分（改一个阶段等于改功能），
// 存进表里就变成「老项目一份、新项目一份」，两边的报告章节不一样却都不报错。
// consult_stages 那张表只存「某个项目在某个阶段干到哪了」。
//
// **例外是 `method` 和 `deliverables` 两栏**：它们是纯文字（一条进 prompt、同时原样显示
// 给用户），后台可以逐步改（088 + `stageOverrides.ts`），这里那份是缺省值。所以：
// **读这两栏一律走 `stages()` / `stageByKey()`，不要直接用 `STAGE_DEFAULTS`。**
// 直接读缺省的那一处会变成「后台显示改过了，发给模型的还是旧口径」—— 而那种正文
// 每节都在、表格也满，对着后台那份新操法数不出任何缺失。名字从 `STAGES` 改成
// `STAGE_DEFAULTS` 就是为了让漏改的调用点编译不过。
//
// 三条车道（作者拍板）：
// - fast「四看」= 找事实，对错取决于用户给的资料，没什么可选的 → AI 直接出结论草稿，
//   用户 review / 改 / 补料就定稿。
// - slow「四问 + 四大成」= 做判断，取决于人的取舍 → 必须走「候选方向 → 聊 → 定稿」。
//   全部阶段都走慢车道的话，一个项目要认真聊十几次，用户会直接放弃。
// - plan「第二层 / 第三层」= 承接已定稿的占位系统结论，往下翻译成能上手做的方案。
//   它既不是找事实也不是二选一的取舍，所以**单独一条车道而不是塞进 fast**：
//   fast 的 prompt 写着「四看是找事实，不要发挥」，拿它出内容/数字化方案的话模型会
//   只敢复述上游结论，交出一份没有平台、没有排期的综述 —— 而那份综述读起来完全正常。
import { loadStageOverrides } from './stageOverrides.js';

export type StageLane = 'fast' | 'slow' | 'plan';
// 分组名是数据不是排版：它原样进 prompt（「这一步属于「${stage.group}」」）、也是左栏
// 分组标题的来源。这个 union 一度还写着改名前的「内容创作 / 数字化营销」，而下面的
// STAGES 里早就是「第二层 / 第三层」—— tsc 报着错但 tsx 照跑，所以两边不一致谁都没发现。
export type StageGroup = '四看' | '四问' | '四大成' | '第二层' | '第三层';

/** 车道的中文名。报错文案用它 —— 只说「车道不对」用户不知道该点哪个按钮。 */
export const LANE_LABEL: Record<StageLane, string> = {
  fast: '咨询',
  slow: '分析',
  plan: '执行',
};

export interface StageDef {
  key: string;
  label: string;
  group: StageGroup;
  lane: StageLane;
  /** 这一步在回答什么 —— 直接显示给用户，也进 prompt */
  question: string;
  /** 解锁前提：这些阶段全部 decided 之后才允许开工 */
  requires: string[];
  /**
   * 这一步的 prompt 里**要带整份正文**的上游阶段（不填 = 跟 `requires` 一样）。
   *
   * 从 `requires` 里拆出来，因为那一个字段原来管三件事：解锁条件、stale 传递、
   * 带哪几份正文进 prompt。三件事的答案并不一样 —— 「内容营销战略」必须等品牌屋定稿
   * （解锁），但它真正要读的是**看用户**那张画像卡（触点偏好、决策链里的谁付钱/谁使用）
   * 和**看竞品**那几张对标卡（对手的渠道与内容打法），而品牌屋的正文只是上游结论的
   * 汇总表。为了带上画像卡去往 requires 里加 `audience` 的话，解锁条件也跟着变了；
   * 不加的话模型手里只有一句话总结 —— 它会**编一份画像和一组平台偏好**，读起来完全
   * 正常（标签、时段、爱看什么都写得很具体），而整份内容方案就投在编出来的人身上。
   *
   * 带哪几份是取舍不是清单：全带上的话上下文被表格占满，客户资料被挤到最后面，
   * 模型开始照常识写（同 `knowledgeBlock` 的注释）。所以只带这一步真的要逐格读的那几份。
   */
  contextBodies?: string[];
  /**
   * 这一步该**怎么想** —— 方法论各模块的「操法 / 判断标准」（§1.1 / §1.2 / §1.3）。
   *
   * 和 deliverables 是两件事：deliverables 说「要交出什么」，method 说「按什么顺序推出来」。
   * 只给清单不给操法的后果是**表格填满了但推导是模型自己编的** —— 价值主张那一节
   * 三层都在，却从没做过「三问检验」，也没判过「现在卡在哪一层」；竞品六家各写了三条
   * 不同的维度。这类正文在界面上和照方法论推出来的一模一样，顾问照样拿去用。
   * 所以它和 deliverables 一起进 prompt，也一起显示给用户。
   */
  method: string[];
  /**
   * 这一步必须产出的东西（品牌占位方法论 §1.1 / §1.2 / §1.3 的「输出物」）。
   *
   * **这份清单就是 prompt**：不写清楚的话模型回的是一段通顺的综述 —— 读起来完全正常，
   * 但没有企业现状卡、没有痛点优先级矩阵、没有数据置信度表，而这些才是方案里
   * 顾问真正要用的东西。它同时显示给用户当「本步应产出」勾选表，因为
   * 「模型漏了第 4 项」只有对着清单才看得出来。
   */
  deliverables: string[];
  /**
   * 定稿之后在对话里**直接摊开**的那一节（按 body 里 `## N. 标题` 的标题关键词认）。
   *
   * 定稿气泡原来摊的是 rationale + evidence，那两段是给模型看的推导过程（几百字的
   * 因果链和原文摘录），顾问要用的东西全在正文的表里 —— 于是那张表要多点一次
   * 「在右侧查看完整正文」才看得到，而气泡已经很长了，看起来像「定稿就是这些」。
   *
   * 关键词必须是 `deliverables` 里那一项的**前缀原词**（如「企业现状卡」对上
   * `## 1. 企业现状卡（表格：…）`）：对不上的话 `sectionOf` 返回空，
   * 而气泡里会明说「没找到这一节」—— 不能静默省掉，省掉读起来就是「这一版没这张表」。
   * 不填 = 这一步只摊一句话结论（慢车道那几步的正文是取舍过程，摘一节没有意义）。
   */
  highlight?: string;
}

