const BY_KEY = new Map(STAGES.map((s) => [s.key, s]));

export function stageByKey(key: string): StageDef | undefined {
  return BY_KEY.get(key);
}

/**
 * 这个阶段能不能开工。`decided` 是已定稿的 stage_key 集合。
 *
 * 缺前提时返回缺的是哪几个 —— 只回一个 false 的话界面只能写「未解锁」，
 * 用户不知道要先去做哪一步，会当成功能坏了。
 */
export function unlockState(
  stage: StageDef,
  decided: Set<string>
): { unlocked: boolean; missing: string[] } {
  const missing = stage.requires.filter((k) => !decided.has(k));
  return { unlocked: missing.length === 0, missing };
}

/**
 * 某个阶段的全部下游（传递闭包）—— 它的结论改了之后要打 stale 的那些。
 *
 * 由 requires 反推而不是另写一份 affects：两份手写的依赖表迟早对不上，
 * 而对不上的表现是「改了定位，价值主张没被标 stale」，报告里两节口径矛盾，
 * 一句错都不报。
 *
 * 一遍扫描成立的前提是 STAGES 的顺序是拓扑序（requires 只指向前面的阶段）。
 * 新增阶段时把它插在它依赖的阶段之后，否则下游会漏标 —— 同上，不报错。
 */
export function downstreamOf(key: string): string[] {
  const out: string[] = [];
  const dirty = new Set([key]);
  for (const s of STAGES) {
    if (s.key === key) continue;
    if (s.requires.some((r) => dirty.has(r))) {
      dirty.add(s.key);
      out.push(s.key);
    }
  }
  return out;
}
