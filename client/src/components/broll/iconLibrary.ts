const byTag = new Map<string, IconDef>()
for (const i of ICONS) for (const t of i.tags) if (!byTag.has(t)) byTag.set(t, i)
/** 关键词或图标名 → 图标；都对不上返回 null（调用方要报出来，不能画个空位） */
export const findIcon = (key: string) => byTag.get(key.trim()) || byId.get(key.trim()) || null
/** 给服务端 / 面板用的关键词表：每个图标取第一个关键词当代表 */
